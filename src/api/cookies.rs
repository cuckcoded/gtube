//! Minimal cookie jar with Netscape `cookies.txt` import/export.
//!
//! The same file is handed to yt-dlp (playback through mpv, downloads), so the
//! format must stay compatible with what yt-dlp reads.

use std::fmt::Write as _;

#[derive(Clone, Debug)]
pub struct Cookie {
    pub domain: String,
    pub include_subdomains: bool,
    pub path: String,
    pub secure: bool,
    pub http_only: bool,
    pub expires: i64,
    pub name: String,
    pub value: String,
}

#[derive(Clone, Debug, Default)]
pub struct CookieJar {
    cookies: Vec<Cookie>,
}

impl CookieJar {
    pub fn parse_netscape(text: &str) -> Self {
        let mut cookies = Vec::new();
        for line in text.lines() {
            let mut line = line.trim_end_matches('\r');
            let mut http_only = false;
            if let Some(rest) = line.strip_prefix("#HttpOnly_") {
                line = rest;
                http_only = true;
            } else if line.starts_with('#') || line.trim().is_empty() {
                continue;
            }
            let parts: Vec<&str> = line.split('\t').collect();
            if parts.len() < 7 {
                continue;
            }
            cookies.push(Cookie {
                domain: parts[0].to_string(),
                include_subdomains: parts[1].eq_ignore_ascii_case("TRUE"),
                path: parts[2].to_string(),
                secure: parts[3].eq_ignore_ascii_case("TRUE"),
                http_only,
                expires: parts[4].parse().unwrap_or(0),
                name: parts[5].to_string(),
                value: parts[6..].join("\t"),
            });
        }
        Self { cookies }
    }

    pub fn to_netscape(&self) -> String {
        let mut out = String::from("# Netscape HTTP Cookie File\n# Generated by GTube. Do not share this file.\n\n");
        for c in &self.cookies {
            let _ = writeln!(
                out,
                "{}{}\t{}\t{}\t{}\t{}\t{}\t{}",
                if c.http_only { "#HttpOnly_" } else { "" },
                c.domain,
                if c.include_subdomains { "TRUE" } else { "FALSE" },
                c.path,
                if c.secure { "TRUE" } else { "FALSE" },
                c.expires,
                c.name,
                c.value
            );
        }
        out
    }

    #[cfg_attr(not(feature = "webkit"), allow(dead_code))]
    pub fn from_cookies(cookies: Vec<Cookie>) -> Self {
        Self { cookies }
    }

    pub fn retain(&mut self, f: impl Fn(&Cookie) -> bool) {
        self.cookies.retain(|c| f(c));
    }

    pub fn is_empty(&self) -> bool {
        self.cookies.is_empty()
    }

    fn domain_matches(cookie_domain: &str, host: &str) -> bool {
        let d = cookie_domain.trim_start_matches('.');
        host == d || host.ends_with(&format!(".{d}"))
    }

    /// Returns the value of a cookie that applies to `host`.
    pub fn get(&self, host: &str, name: &str) -> Option<&str> {
        let now = now_secs();
        self.cookies
            .iter()
            .filter(|c| c.name == name && Self::domain_matches(&c.domain, host))
            .filter(|c| c.expires == 0 || c.expires > now)
            .map(|c| c.value.as_str())
            .next()
    }

    pub fn set(&mut self, domain: &str, name: &str, value: &str) {
        self.cookies.retain(|c| !(c.name == name && c.domain == domain));
        self.cookies.push(Cookie {
            domain: domain.to_string(),
            include_subdomains: domain.starts_with('.'),
            path: "/".into(),
            secure: true,
            http_only: false,
            expires: now_secs() + 3600 * 24 * 365,
            name: name.to_string(),
            value: value.to_string(),
        });
    }

    /// `Cookie:` header value for requests to `host`.
    pub fn header_for(&self, host: &str) -> String {
        let now = now_secs();
        let mut seen = std::collections::HashSet::new();
        let mut parts = Vec::new();
        for c in &self.cookies {
            if !Self::domain_matches(&c.domain, host) || (c.expires != 0 && c.expires <= now) {
                continue;
            }
            if seen.insert(c.name.clone()) {
                parts.push(format!("{}={}", c.name, c.value));
            }
        }
        parts.join("; ")
    }

    pub fn has_login(&self) -> bool {
        self.get("www.youtube.com", "SAPISID").is_some()
            || self.get("www.youtube.com", "__Secure-3PAPISID").is_some()
    }
}

pub fn now_secs() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0)
}
